import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const processedDir = new URL("../measurements/processed/", import.meta.url);
const rawDir = new URL("../measurements/raw/", import.meta.url);

const timingFiles = [
  "whiteboard_home-unrestricted",
  "gods-hand_home-unrestricted",
  "robotic-arm-v2_home-unrestricted",
  "whiteboard_limited-emulated",
  "gods-hand_limited-emulated",
  "robotic-arm-v2_limited-emulated",
];

const gas = JSON.parse(await readFile(new URL("gas-local-hardhat.summary.json", processedDir), "utf8"));

function parseCsvLine(line) {
  const values = [];
  let value = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const character = line[index];
    if (character === '"') {
      if (quoted && line[index + 1] === '"') {
        value += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === "," && !quoted) {
      values.push(value);
      value = "";
    } else {
      value += character;
    }
  }
  values.push(value);
  return values;
}

const timingRows = [];
for (const stem of timingFiles) {
  const summary = JSON.parse(await readFile(new URL(`${stem}.summary.json`, processedDir), "utf8"));
  const series = summary.series[0];
  const raw = (await readFile(new URL(`${stem}.csv`, rawDir), "utf8"))
    .trim()
    .split(/\r?\n/)
    .slice(1)
    .map(parseCsvLine);
  const firstRecorded = raw.find((row) => row[17] === "1") ?? raw[3];
  const metrics = series.metrics;
  timingRows.push({
    model: series.configuration.fileName,
    profile: series.configuration.networkProfile,
    fileSizeBytes: Number(firstRecorded[16]),
    successes: series.recordedSuccessful,
    failures: series.recordedFailed,
    onlineMedianMs: metrics.onlineTotalMs.median,
    onlineQ1Ms: metrics.onlineTotalMs.q1,
    onlineQ3Ms: metrics.onlineTotalMs.q3,
    onlineP95Ms: metrics.onlineTotalMs.p95,
    offlineMedianMs: metrics.offlineTotalMs.median,
    offlineP95Ms: metrics.offlineTotalMs.p95,
    source: `measurements/raw/${stem}.csv`,
  });
}

function csvValue(value) {
  const text = String(value);
  return /[",\r\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

const timingHeader = Object.keys(timingRows[0]);
const timingCsv = [
  timingHeader.join(","),
  ...timingRows.map((row) => timingHeader.map((key) => csvValue(row[key])).join(",")),
].join("\n") + "\n";

const gasRows = gas.batches.map((batch) => ({
  batchSize: batch.batchSize,
  repetitions: batch.repetitions,
  individualGasPerModelMedian: batch.individualGasPerModel.median,
  merkleGasPerModelMedian: batch.merkleGasPerModel.median,
  merkleSavingPct: batch.medianPerModelSavingPct,
}));
const gasHeader = Object.keys(gasRows[0]);
const gasCsv = [
  gasHeader.join(","),
  ...gasRows.map((row) => gasHeader.map((key) => csvValue(row[key])).join(",")),
].join("\n") + "\n";

const format = (value) => Number(value).toFixed(2);
const timingMarkdown = [
  "# BidSphere benchmark overview",
  "",
  "Generated from the six timing summaries and the local Hardhat gas summary.",
  "",
  "## Timing measurements",
  "",
  "| Model | Profile | Size [bytes] | Successes | Failures | Online median [ms] | Online p95 [ms] | Offline median [ms] | Offline p95 [ms] |",
  "|---|---|---:|---:|---:|---:|---:|---:|---:|",
  ...timingRows.map((row) => `| ${row.model} | ${row.profile} | ${row.fileSizeBytes} | ${row.successes} | ${row.failures} | ${format(row.onlineMedianMs)} | ${format(row.onlineP95Ms)} | ${format(row.offlineMedianMs)} | ${format(row.offlineP95Ms)} |`),
  "",
  "## Gas measurements",
  "",
  "| Batch size | Repetitions | Individual gas/model median | Merkle gas/model median | Merkle saving [%] |",
  "|---:|---:|---:|---:|---:|",
  ...gasRows.map((row) => `| ${row.batchSize} | ${row.repetitions} | ${format(row.individualGasPerModelMedian)} | ${format(row.merkleGasPerModelMedian)} | ${format(row.merkleSavingPct)} |`),
  "",
  "Sources: `measurements/raw/*.csv`; timing summaries generated by `npm run analyze:benchmark`; gas summary generated by `scripts/analyze-gas-benchmark.mjs`.",
  "",
].join("\n");

await writeFile(new URL("benchmark-timing-overview.csv", processedDir), timingCsv, "utf8");
await writeFile(new URL("benchmark-gas-overview.csv", processedDir), gasCsv, "utf8");
await writeFile(new URL("benchmark-overview.md", processedDir), timingMarkdown, "utf8");
console.log("Saved timing CSV, gas CSV, and Markdown overview.");
